// TimeMixer, single variable, integer datapath.
//
// Four scales (96, 48, 24, 12) come from average pooling. Each scale is
// instance normalised, embedded by a length-3 circular convolution into 16
// channels, then two PDM blocks decompose it into season and trend, mix seasons
// bottom up and trends top down, sum the two, add the block input and run a
// 16->32->16 gate. Every scale projects to the horizon on its own, the channel
// axis collapses to one value, the four predictions are summed and the result is
// denormalised with the level-0 statistics.
//
// One buffer word holds all sixteen channels of one time step, so a scale owns T
// consecutive words at its own base. Layers along the time axis give every lane
// one channel and broadcast the coefficient; the gate runs along the channel
// axis, so there every lane is one output channel and the coefficients arrive as
// one packed 256-bit word from the gate rom.
//
// Weights are Q14, activations Q12, accumulators 44 bits, one saturation on the
// way back to Q12. The offsets in tm_offsets.vh are generated by
// timemixer_ref.py, which is also the model the testbench compares against.
//
// Every large array is a single-write, single-read block RAM (dpram, the same
// shape as rtl/src/dpram.v). Its read is registered, so a state that consumes an
// array presents the address one cycle before the arithmetic uses it: the first
// cycle in such a state only drives the address, and the pipeline then asks for
// index + 1 while the arithmetic works on index.
`timescale 1ns / 1ps


module timemixer_top (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        start,
    input  wire        ld_en,
    input  wire [1:0]  ld_sel,    // 0: weight rom, 1: gate rom, 2: input
    input  wire [16:0] ld_addr,
    input  wire [15:0] ld_data,
    input  wire [3:0]  ld_sub,    // 16-bit slice of a gate word
    output wire        done,
    input  wire [6:0]  rd_addr,
    output wire signed [15:0] rd_data
);
    localparam integer L    = 96;
    localparam integer DM   = 16;
    localparam integer DFF  = 32;
    localparam integer PRED = 96;
    localparam integer WQ   = 14;
    localparam integer DQ   = 12;

    localparam integer B0 = 0, B1 = 96, B2 = 144, B3 = 168;

    `include "tm_offsets.vh"

    localparam [4:0] S_IDLE = 0, S_GL = 1, S_POOL = 2, S_NSUM = 3, S_NDIV = 4,
                     S_NSQ = 5, S_NDIV2 = 6, S_NSQRT = 7, S_NINV = 8, S_NAP = 9,
                     S_EMB = 10, S_DEC0 = 11, S_DEC = 12, S_MIXA = 13,
                     S_MIXB = 14, S_MIXG = 15, S_MIXC = 16, S_COMB = 17, S_MIXG2 = 26,
                     S_GATE1 = 18, S_GATG = 19, S_GATE2 = 20, S_GATE3 = 21,
                     S_COMB2 = 22, S_PRED = 23, S_DEN = 24, S_DONE = 25;

    reg [4:0]  st;
    reg [9:0]  i;
    reg [7:0]  t, o, c;
    reg [1:0]  sc, lev, grp, k;
    reg [1:0]  dir;        // 0: season chain, 1: trend chain
    reg [3:0]  ph;

    // ---- memories ---------------------------------------------------------
    wire         wm_we;
    wire  [16:0]  wm_wa;
    wire  [15:0]  wm_wd;
    wire [15:0]  wm_q;

    wire         gm_we;
    wire  [7:0]   gm_wa;
    wire  [255:0] gm_wd;
    wire [255:0] gm_q;

    reg          am_we;
    reg  [7:0]   am_wa;
    reg  [255:0] am_wd;
    wire [255:0] am_q;

    reg          sm_we;
    reg  [7:0]   sm_wa;
    reg  [255:0] sm_wd;
    wire [255:0] sm_q;

    reg          tm_we;
    reg  [7:0]   tm_wa;
    reg  [255:0] tm_wd;
    wire [255:0] tm_q;

    reg          rm_we;
    reg  [6:0]   rm_wa;
    reg  [255:0] rm_wd;
    wire [255:0] rm_q;

    reg          xm_we;
    reg  [7:0]   xm_wa;
    reg  [15:0]  xm_wd;
    wire [15:0]  xm_q;

    reg          nm_we;
    reg  [7:0]   nm_wa;
    reg  [15:0]  nm_wd;
    wire [15:0]  nm_q;

    // read addresses, presented for the cycle after this one
    reg  [16:0]  wr;
    reg  [7:0]   gr, ar, sr, tr_, nr, xr;
    reg  [6:0]   rr;

    reg [15:0]   embw [0:47];
    reg [255:0]  gws;

    dpram #(.WIDTH(16),  .DEPTH(WROM), .AW(17)) u_wmem (
        .clk(clk), .we(wm_we), .waddr(wm_wa), .wdata(wm_wd),
        .raddr(wr), .rdata(wm_q));

    dpram #(.WIDTH(256), .DEPTH(256), .AW(8)) u_gwm (
        .clk(clk), .we(gm_we), .waddr(gm_wa), .wdata(gm_wd),
        .raddr(gr), .rdata(gm_q));

    dpram #(.WIDTH(256), .DEPTH(256), .AW(8)) u_act (
        .clk(clk), .we(am_we), .waddr(am_wa), .wdata(am_wd),
        .raddr(ar), .rdata(am_q));

    dpram #(.WIDTH(256), .DEPTH(256), .AW(8)) u_seas (
        .clk(clk), .we(sm_we), .waddr(sm_wa), .wdata(sm_wd),
        .raddr(sr), .rdata(sm_q));

    dpram #(.WIDTH(256), .DEPTH(256), .AW(8)) u_trnd (
        .clk(clk), .we(tm_we), .waddr(tm_wa), .wdata(tm_wd),
        .raddr(tr_), .rdata(tm_q));

    dpram #(.WIDTH(256), .DEPTH(128), .AW(7)) u_scr (
        .clk(clk), .we(rm_we), .waddr(rm_wa), .wdata(rm_wd),
        .raddr(rr), .rdata(rm_q));

    dpram #(.WIDTH(16),  .DEPTH(256), .AW(8)) u_xbuf (
        .clk(clk), .we(xm_we), .waddr(xm_wa), .wdata(xm_wd),
        .raddr(xr), .rdata(xm_q));

    dpram #(.WIDTH(16),  .DEPTH(256), .AW(8)) u_nbuf (
        .clk(clk), .we(nm_we), .waddr(nm_wa), .wdata(nm_wd),
        .raddr(nr), .rdata(nm_q));

    // ---- registers --------------------------------------------------------
    reg [15:0]  xin  [0:L-1];
    reg signed [15:0] hid [0:DFF-1];
    reg signed [15:0] meanv [0:3];
    reg signed [15:0] stdv  [0:3];
    reg signed [31:0] invv  [0:3];
    reg signed [15:0] outv  [0:PRED-1];
    reg signed [15:0] gl    [0:GELU_N-1];

    reg signed [43:0] acc  [0:DM-1];
    reg signed [43:0] wsum [0:DM-1];
    reg signed [63:0] sum1, sum2, psum;
    reg signed [17:0] win;

    reg [255:0] dcur, dadd, prow;
    reg signed [15:0] nw0, nw1, nw2;
    reg signed [15:0] xbp;
    reg signed [15:0] projb;

    // ---- sizes and weight offsets -----------------------------------------
    function [7:0] slen;
        input [1:0] s;
        begin
            slen = (s == 2'd0) ? 8'd96 : (s == 2'd1) ? 8'd48 :
                   (s == 2'd2) ? 8'd24 : 8'd12;
        end
    endfunction

    function [7:0] sbase;
        input [1:0] s;
        begin
            sbase = (s == 2'd0) ? B0 : (s == 2'd1) ? B1 : (s == 2'd2) ? B2 : B3;
        end
    endfunction

    function [16:0] down0;
        input [1:0] blk;
        input [1:0] lv;
        begin
            case ({blk, lv})
            4'd0: down0 = O_B0_DOWN0_0; 4'd1: down0 = O_B0_DOWN1_0;
            4'd2: down0 = O_B0_DOWN2_0; 4'd4: down0 = O_B1_DOWN0_0;
            4'd5: down0 = O_B1_DOWN1_0; 4'd6: down0 = O_B1_DOWN2_0;
            default: down0 = 0;
            endcase
        end
    endfunction

    function [16:0] down2;
        input [1:0] blk;
        input [1:0] lv;
        begin
            case ({blk, lv})
            4'd0: down2 = O_B0_DOWN0_2; 4'd1: down2 = O_B0_DOWN1_2;
            4'd2: down2 = O_B0_DOWN2_2; 4'd4: down2 = O_B1_DOWN0_2;
            4'd5: down2 = O_B1_DOWN1_2; 4'd6: down2 = O_B1_DOWN2_2;
            default: down2 = 0;
            endcase
        end
    endfunction

    function [16:0] up0;
        input [1:0] blk;
        input [1:0] lv;
        begin
            case ({blk, lv})
            4'd0: up0 = O_B0_UP0_0; 4'd1: up0 = O_B0_UP1_0;
            4'd2: up0 = O_B0_UP2_0; 4'd4: up0 = O_B1_UP0_0;
            4'd5: up0 = O_B1_UP1_0; 4'd6: up0 = O_B1_UP2_0;
            default: up0 = 0;
            endcase
        end
    endfunction

    function [16:0] up2;
        input [1:0] blk;
        input [1:0] lv;
        begin
            case ({blk, lv})
            4'd0: up2 = O_B0_UP0_2; 4'd1: up2 = O_B0_UP1_2;
            4'd2: up2 = O_B0_UP2_2; 4'd4: up2 = O_B1_UP0_2;
            4'd5: up2 = O_B1_UP1_2; 4'd6: up2 = O_B1_UP2_2;
            default: up2 = 0;
            endcase
        end
    endfunction

    function [16:0] predw;
        input [1:0] s;
        begin
            case (s)
            2'd0: predw = O_PRED0; 2'd1: predw = O_PRED1;
            2'd2: predw = O_PRED2; default: predw = O_PRED3;
            endcase
        end
    endfunction

    // ---- mixing geometry --------------------------------------------------
    function [7:0] mlen;       // source length along the time axis
        input [1:0] d;
        input [1:0] lv;
        begin
            mlen = (d == 2'd0) ? slen(lv) : slen(3 - lv);
        end
    endfunction

    function [7:0] mout;       // output length along the time axis
        input [1:0] d;
        input [1:0] lv;
        begin
            mout = (d == 2'd0) ? slen(lv + 2'd1) : slen(2 - lv);
        end
    endfunction

    function [1:0] msl;        // scale the source buffer lives at
        input [1:0] d;
        input [1:0] lv;
        begin
            msl = (d == 2'd0) ? (lv + 2'd1) : (2 - lv);
        end
    endfunction

    function [16:0] mw1;       // first layer coefficient
        input [1:0] d;
        input [1:0] lv;
        input [7:0] oo;
        input [7:0] tt;
        reg [16:0] b, p;
        begin
            b = (d == 2'd0) ? down0(k, lv) : up0(k, lv);
            p = oo * ((d == 2'd0) ? slen(lv) : slen(3 - lv));
            mw1 = b + p + tt;
        end
    endfunction

    function [16:0] mb1;       // first layer bias row
        input [1:0] d;
        input [1:0] lv;
        input [7:0] oo;
        reg [16:0] b, p;
        begin
            b = (d == 2'd0) ? down0(k, lv) : up0(k, lv);
            p = ((d == 2'd0) ? slen(lv + 2'd1) : slen(2 - lv)) *
                ((d == 2'd0) ? slen(lv) : slen(3 - lv));
            mb1 = b + p + oo;
        end
    endfunction

    function [16:0] mw2;       // second layer coefficient
        input [1:0] d;
        input [1:0] lv;
        input [7:0] oo;
        input [7:0] tt;
        reg [16:0] b, p;
        begin
            b = (d == 2'd0) ? down2(k, lv) : up2(k, lv);
            p = oo * ((d == 2'd0) ? slen(lv + 2'd1) : slen(2 - lv));
            mw2 = b + p + tt;
        end
    endfunction

    function [16:0] mb2;       // second layer bias row
        input [1:0] d;
        input [1:0] lv;
        input [7:0] oo;
        reg [16:0] b, p;
        begin
            b = (d == 2'd0) ? down2(k, lv) : up2(k, lv);
            p = ((d == 2'd0) ? slen(lv + 2'd1) : slen(2 - lv)) *
                ((d == 2'd0) ? slen(lv + 2'd1) : slen(2 - lv));
            mb2 = b + p + oo;
        end
    endfunction

    function [7:0] wrp;        // x - m when x >= m, x < 2m
        input [7:0] x;
        input [7:0] m;
        begin
            wrp = (x >= m) ? (x - m) : x;
        end
    endfunction

    function [7:0] deca;       // 25-tap window index with replicate padding
        input [9:0] x;
        input [1:0] s;
        reg [9:0] d, lim;
        begin
            d = x - 10'd12;
            lim = {2'd0, slen(s)} - 10'd1;
            if (x < 10'd12) deca = 8'd0;
            else if (d > lim) deca = slen(s) - 8'd1;
            else deca = d[7:0];
        end
    endfunction

    function [7:0] dhi;        // min(t + 13, len - 1)
        input [7:0] x;
        input [1:0] s;
        begin
            if ((x + 8'd13) > (slen(s) - 8'd1)) dhi = slen(s) - 8'd1;
            else dhi = x + 8'd13;
        end
    endfunction

    function [7:0] dlo;        // max(t - 12, 0)
        input [7:0] x;
        begin
            if (x < 8'd12) dlo = 8'd0;
            else dlo = x - 8'd12;
        end
    endfunction

    // ---- arithmetic helpers ----------------------------------------------
    function signed [15:0] sat;
        input signed [63:0] v;
        begin
            if (v > 63'sd32767) sat = 16'sd32767;
            else if (v < -63'sd32768) sat = -16'sd32768;
            else sat = v[15:0];
        end
    endfunction

    function signed [15:0] shr;
        input signed [63:0] v;
        input integer sh;
        begin
            shr = sat(v >>> sh);
        end
    endfunction

    function signed [15:0] gelu_of;
        input signed [15:0] v;
        integer idx;
        begin
            idx = (v >>> GELU_STEP) + GELU_OFF;
            if (idx < 0) idx = 0;
            else if (idx >= GELU_N) idx = GELU_N - 1;
            gelu_of = gl[idx];
        end
    endfunction

    function [15:0] lane;
        input [255:0] w;
        input integer n;
        begin
            lane = w[n*16 +: 16];
        end
    endfunction

    // ---- divider and square root -----------------------------------------
    reg  [31:0] dv_arg, dv_den, dv_num, dv_q, dv_r;
    reg  [5:0]  dv_cnt;
    reg         dv_go, dv_busy, dv_done;
    reg  [39:0] sq_arg, sq_x, sq_res, sq_bit;
    reg         sq_go, sq_busy, sq_done;
    reg         sgn;

    always @(posedge clk) begin
        if (!rst_n) begin
            dv_q <= 0; dv_r <= 0; dv_num <= 0; dv_den <= 1; dv_cnt <= 0;
            dv_busy <= 0; dv_done <= 0;
        end else begin
            dv_done <= 1'b0;
            if (dv_go) begin
                dv_num <= dv_arg; dv_den <= (win == 0) ? 32'd1 : {14'd0, win};
                dv_q <= 0; dv_r <= 0; dv_cnt <= 0; dv_busy <= 1'b1;
            end else if (dv_busy) begin
                if ({dv_r[30:0], dv_num[31]} >= dv_den) begin
                    dv_r <= {dv_r[30:0], dv_num[31]} - dv_den;
                    dv_q <= {dv_q[30:0], 1'b1};
                end else begin
                    dv_r <= {dv_r[30:0], dv_num[31]};
                    dv_q <= {dv_q[30:0], 1'b0};
                end
                dv_num <= {dv_num[30:0], 1'b0};
                dv_cnt <= dv_cnt + 1;
                if (dv_cnt == 6'd31) begin dv_busy <= 1'b0; dv_done <= 1'b1; end
            end
        end
    end

    always @(posedge clk) begin
        if (!rst_n) begin
            sq_x <= 0; sq_res <= 0; sq_bit <= 0; sq_busy <= 0; sq_done <= 0;
        end else begin
            sq_done <= 1'b0;
            if (sq_go) begin
                sq_x <= sq_arg; sq_res <= 0; sq_bit <= 40'h40_0000_0000;
                sq_busy <= 1'b1;
            end else if (sq_busy) begin
                if (sq_bit == 0) begin sq_busy <= 1'b0; sq_done <= 1'b1; end
                else begin
                    if (sq_x >= sq_res + sq_bit) begin
                        sq_x   <= sq_x - (sq_res + sq_bit);
                        sq_res <= (sq_res >> 1) + sq_bit;
                    end else sq_res <= (sq_res >> 1);
                    sq_bit <= (sq_bit == 1) ? 40'd0 : (sq_bit >> 2);
                end
            end
        end
    end

    // ---- host loads -------------------------------------------------------
    // The embedding table is read 48 words at a time, so a register copy is
    // kept next to the weight rom. The gate rom arrives as sixteen 16-bit
    // slices and is assembled in a shadow register before one word is written.
    reg [255:0] gwd_c;

    always @* begin
        gwd_c = gws;
        gwd_c[ld_sub*16 +: 16] = ld_data;
    end

    assign wm_we = ld_en && (ld_sel == 2'd0);
    assign wm_wa = ld_addr;
    assign wm_wd = ld_data;

    assign gm_we = ld_en && (ld_sel == 2'd1) && (ld_sub == 4'd15);
    assign gm_wa = ld_addr[7:0];
    assign gm_wd = gwd_c;

    always @(posedge clk) begin
        if (ld_en) begin
            if (ld_sel == 2'd0) begin
                if (ld_addr >= O_EMB && ld_addr < (O_EMB + 48))
                    embw[ld_addr[5:0]] <= ld_data;
            end else if (ld_sel == 2'd1) gws[ld_sub*16 +: 16] <= ld_data;
            else xin[ld_addr[7:0]] <= ld_data;
        end
    end

    assign rd_data = outv[rd_addr];
    assign done = (st == S_DONE);

    // ---- read ports -------------------------------------------------------
    always @* begin
        wr = 17'd0; gr = 8'd0; ar = 8'd0; sr = 8'd0; tr_ = 8'd0;
        rr = 7'd0; xr = 8'd0; nr = 8'd0;
        case (st)
        S_GL: begin
            wr = (ph == 4'd0) ? 17'd0 : ({7'd0, i} + 17'd1);
        end
        S_POOL: begin
            if (t >= 8'd193) xr = 8'd144 + (t - 8'd193);
            else if (t >= 8'd144) xr = 8'd96 + (t - 8'd144);
        end
        S_NSUM, S_NSQ, S_NAP: begin
            xr = (ph == 4'd0) ? sbase(sc) : (sbase(sc) + t + 8'd1);
        end
        S_EMB: begin
            if (ph == 4'd0) nr = sbase(sc) + slen(sc) - 8'd1;
            else if (ph == 4'd1) nr = sbase(sc);
            else if (ph == 4'd2) nr = sbase(sc) + 8'd1;
            else if (ph == 4'd3) nr = sbase(sc) + 8'd2;
            else nr = sbase(sc) + wrp(t + 8'd3, slen(sc));
        end
        S_DEC0: begin
            ar = sbase(sc) + ((ph == 4'd0) ? 8'd0 : deca({2'd0, i} + 10'd1, sc));
        end
        S_DEC: begin
            if (ph == 4'd0) ar = sbase(sc);
            else if (ph == 4'd1) ar = sbase(sc) + dhi(t, sc);
            else if (ph == 4'd2) ar = sbase(sc) + dlo(t);
            else ar = sbase(sc) + t + 8'd1;
        end
        S_MIXB: begin
            sr = sbase(lev);
            tr_ = sbase(3 - lev);
            if (ph == 4'd0) wr = mw1(dir, lev, o, 8'd0);
            else if ((t + 8'd1) >= mlen(dir, lev)) wr = mb1(dir, lev, o);
            else begin
                wr = mw1(dir, lev, o, t + 8'd1);
                sr = sbase(lev) + t + 8'd1;
                tr_ = sbase(3 - lev) + t + 8'd1;
            end
        end
        S_MIXG: begin
            rr = 7'd0;
        end
        S_MIXG2: begin
            rr = (o == (mout(dir, lev) - 8'd1)) ? 7'd0 : ({1'd0, o} + 7'd1);
            if (o == (mout(dir, lev) - 8'd1)) wr = mw2(dir, lev, 8'd0, 8'd0);
        end
        S_MIXC: begin
            if ((t + 8'd1) >= mout(dir, lev)) begin
                wr = mb2(dir, lev, o);
                sr = sbase(msl(dir, lev)) + o;
                tr_ = sbase(msl(dir, lev)) + o;
            end else begin
                wr = mw2(dir, lev, o, t + 8'd1);
                rr = {1'd0, t} + 7'd1;
            end
        end
        S_COMB: begin
            if ((o + 8'd1) >= mout(dir, lev)) begin
                if (dir == 2'd1) begin sr = 8'd0; tr_ = 8'd0; end
            end else begin
                wr = mw2(dir, lev, o + 8'd1, 8'd0);
            end
        end
        S_COMB2: begin
            sr = t + 8'd1;
            tr_ = t + 8'd1;
        end
        S_GATE1: begin
            sr = sbase(sc) + t;
            if (ph == 4'd0) gr = k*128 + grp*16;
            else if (c == 8'd15) gr = k*128 + 64 + grp;
            else gr = k*128 + grp*16 + c + 8'd1;
        end
        S_GATE2: begin
            if (ph == 4'd3) gr = k*128 + 32;
            else if (o == 8'd31) begin
                gr = k*128 + 66;
                ar = sbase(sc) + t;
            end else gr = k*128 + 32 + o + 8'd1;
        end
        S_GATE3: begin
            ar = sbase(sc) + t + 8'd1;
            gr = k*128 + 66;
        end
        S_PRED: begin
            if (ph == 4'd0) begin
                wr = predw(sc) + o * slen(sc);
                ar = sbase(sc);
            end else if (ph == 4'd1) begin
                if ((t + 8'd1) >= slen(sc)) wr = predw(sc) + PRED * slen(sc) + o;
                else begin
                    wr = predw(sc) + o * slen(sc) + t + 8'd1;
                    ar = sbase(sc) + t + 8'd1;
                end
            end else if (ph == 4'd2) wr = O_PROJ_B;
            else if (ph == 4'd3) wr = O_PROJ;
            else wr = O_PROJ + t + 8'd1;
        end
        default: ;
        endcase
    end

    // ---- write ports ------------------------------------------------------
    integer m;

    always @* begin
        am_we = 1'b0; am_wa = 8'd0; am_wd = 256'd0;
        case (st)
        S_EMB: if (ph >= 4'd4) begin
            am_we = 1'b1;
            am_wa = sbase(sc) + t;
            for (m = 0; m < DM; m = m + 1)
                am_wd[m*16 +: 16] = shr(
                    $signed(nw0) * $signed(embw[m*3 + 0]) +
                    $signed(nw1) * $signed(embw[m*3 + 1]) +
                    $signed(nw2) * $signed(embw[m*3 + 2]), WQ);
        end
        S_GATE3: begin
            am_we = 1'b1;
            am_wa = sbase(sc) + t;
            for (m = 0; m < DM; m = m + 1)
                am_wd[m*16 +: 16] = sat($signed(lane(am_q, m)) +
                    sat((acc[m] >>> WQ) + ($signed(lane(gm_q, m)) >>> (WQ - DQ))));
        end
        default: ;
        endcase
    end

    always @* begin
        sm_we = 1'b0; sm_wa = 8'd0; sm_wd = 256'd0;
        tm_we = 1'b0; tm_wa = 8'd0; tm_wd = 256'd0;
        case (st)
        S_DEC: if (ph == 4'd3) begin
            sm_we = 1'b1; sm_wa = sbase(sc) + t;
            tm_we = 1'b1; tm_wa = sbase(sc) + t;
            for (m = 0; m < DM; m = m + 1) begin
                tm_wd[m*16 +: 16] = shr(wsum[m] * 21'sd671089, 24);
                sm_wd[m*16 +: 16] = sat($signed(lane(dcur, m)) -
                                        shr(wsum[m] * 21'sd671089, 24));
            end
        end
        S_COMB: begin
            if (dir == 2'd0) begin sm_we = 1'b1; sm_wa = sbase(msl(dir, lev)) + o; end
            else begin tm_we = 1'b1; tm_wa = sbase(msl(dir, lev)) + o; end
            for (m = 0; m < DM; m = m + 1) begin
                sm_wd[m*16 +: 16] = sat(sat((acc[m] >>> WQ) +
                    ($signed(wm_q) >>> (WQ - DQ))) +
                    $signed(lane((dir == 2'd0) ? sm_q : tm_q, m)));
                tm_wd[m*16 +: 16] = sm_wd[m*16 +: 16];
            end
        end
        S_COMB2: begin
            sm_we = 1'b1; sm_wa = t;
            for (m = 0; m < DM; m = m + 1)
                sm_wd[m*16 +: 16] = sat($signed(lane(sm_q, m)) + $signed(lane(tm_q, m)));
        end
        default: ;
        endcase
    end

    always @* begin
        rm_we = 1'b0; rm_wa = 7'd0; rm_wd = 256'd0;
        case (st)
        S_MIXG: begin
            rm_we = 1'b1; rm_wa = o[6:0];
            for (m = 0; m < DM; m = m + 1)
                rm_wd[m*16 +: 16] = sat((acc[m] >>> WQ) +
                                        ($signed(wm_q) >>> (WQ - DQ)));
        end
        S_MIXG2: begin
            rm_we = 1'b1; rm_wa = o[6:0];
            for (m = 0; m < DM; m = m + 1)
                rm_wd[m*16 +: 16] = gelu_of($signed(lane(rm_q, m)));
        end
        default: ;
        endcase
    end

    always @* begin
        xm_we = 1'b0; xm_wa = 8'd0; xm_wd = 16'd0;
        if (st == S_POOL) begin
            if (t < 8'd96) begin
                xm_we = 1'b1; xm_wa = t; xm_wd = xin[t];
            end else if (t < 8'd144) begin
                xm_we = 1'b1; xm_wa = t;
                xm_wd = (xin[2*(t - 8'd96)] + xin[2*(t - 8'd96) + 1]) >> 1;
            end else if (t < 8'd193) begin
                if (t >= 8'd146 && !t[0]) begin
                    xm_we = 1'b1;
                    xm_wa = 8'd144 + ((t - 8'd146) >> 1);
                    xm_wd = (xbp + xm_q) >> 1;
                end
            end else begin
                if (t >= 8'd195 && t[0]) begin
                    xm_we = 1'b1;
                    xm_wa = 8'd168 + ((t - 8'd195) >> 1);
                    xm_wd = (xbp + xm_q) >> 1;
                end
            end
        end
    end

    always @* begin
        nm_we = 1'b0; nm_wa = 8'd0; nm_wd = 16'd0;
        if (st == S_NAP && ph != 4'd0) begin
            nm_we = 1'b1;
            nm_wa = sbase(sc) + t;
            nm_wd = shr(($signed(xm_q) - $signed(meanv[sc])) * invv[sc], DQ);
        end
    end

    // ---- sequencer --------------------------------------------------------
    integer n;

    always @(posedge clk) begin
        if (!rst_n) begin
            st <= S_IDLE; i <= 0; t <= 0; o <= 0; c <= 0; sc <= 0; lev <= 0;
            grp <= 0; k <= 0; dir <= 0; ph <= 0; sgn <= 0;
            sum1 <= 0; sum2 <= 0; dv_go <= 0; sq_go <= 0;
            projb <= 0; xbp <= 0; prow <= 0;
            nw0 <= 0; nw1 <= 0; nw2 <= 0; dcur <= 0; dadd <= 0;
            for (n = 0; n < DM; n = n + 1) begin acc[n] <= 0; wsum[n] <= 0; end
        end else begin
            dv_go <= 1'b0;
            sq_go <= 1'b0;

            case (st)
            S_IDLE: if (start) begin st <= S_GL; i <= 0; ph <= 0; end

            // the GELU table leaves the weight rom once, into registers, so all
            // sixteen lanes can look it up in the same cycle
            S_GL: begin
                if (ph == 4'd0) ph <= 4'd1;
                else begin
                    gl[i[8:0]] <= wm_q;
                    if (i < PRED) outv[i] <= 0;
                    if (i == GELU_N - 1) begin
                        i <= 0; t <= 0; ph <= 0; st <= S_POOL;
                    end else i <= i + 1;
                end
            end

            // ---- pooling --------------------------------------------------
            S_POOL: begin
                if (t < 8'd218) begin
                    if (t >= 8'd145) xbp <= xm_q;
                    t <= t + 1;
                end else begin
                    t <= 0; sc <= 0; sum1 <= 0; win <= 0; ph <= 0; st <= S_NSUM;
                end
            end

            // ---- per scale statistics -------------------------------------
            S_NSUM: begin
                if (ph == 4'd0) ph <= 4'd1;
                else if (t < slen(sc)) begin
                    sum1 <= sum1 + $signed(xm_q);
                    t <= t + 1;
                end else begin
                    sgn <= sum1[63];
                    dv_arg <= sum1[63] ? -sum1[31:0] : sum1[31:0];
                    win <= {10'd0, slen(sc)};
                    dv_go <= 1'b1; t <= 0; st <= S_NDIV;
                end
            end
            S_NDIV: if (dv_done) begin
                meanv[sc] <= sgn ? -$signed(dv_q[15:0]) : $signed(dv_q[15:0]);
                sum2 <= 0; t <= 0; win <= {10'd0, slen(sc)}; ph <= 0; st <= S_NSQ;
            end
            S_NSQ: begin
                if (ph == 4'd0) ph <= 4'd1;
                else if (t < slen(sc)) begin
                    sum2 <= sum2 + ($signed(xm_q) - $signed(meanv[sc])) *
                                    ($signed(xm_q) - $signed(meanv[sc]));
                    t <= t + 1;
                end else begin
                    dv_arg <= sum2[31:0];
                    dv_go <= 1'b1; t <= 0; st <= S_NDIV2;
                end
            end
            S_NDIV2: if (dv_done) begin
                sq_arg <= {8'd0, dv_q[31:0]};
                sq_go <= 1'b1; st <= S_NSQRT;
            end
            S_NSQRT: if (sq_done) begin
                stdv[sc] <= (sq_res[15:0] == 0) ? 16'sd1 : $signed(sq_res[15:0]);
                dv_arg <= 32'd16777216;
                win <= (sq_res[15:0] == 0) ? 18'd1 : {2'd0, sq_res[17:0]};
                dv_go <= 1'b1; st <= S_NINV;
            end
            S_NINV: if (dv_done) begin
                invv[sc] <= dv_q[31:0];
                t <= 0; ph <= 0; st <= S_NAP;
            end
            S_NAP: begin
                if (ph == 4'd0) ph <= 4'd1;
                else if (t == slen(sc) - 1) begin
                    t <= 0; sum1 <= 0; ph <= 0;
                    if (sc == 2'd3) begin sc <= 0; st <= S_EMB; end
                    else begin sc <= sc + 1; st <= S_NSUM; end
                end else t <= t + 1;
            end

            // ---- embedding -------------------------------------------------
            // Three consecutive buf words are kept in a shift window; the first
            // four cycles load it, then one word per cycle keeps it rolling.
            S_EMB: begin
                if (ph == 4'd0) ph <= 4'd1;
                else if (ph == 4'd1) begin
                    nw0 <= nm_q; ph <= 4'd2;
                end else if (ph == 4'd2) begin
                    nw1 <= nm_q; ph <= 4'd3;
                end else if (ph == 4'd3) begin
                    nw2 <= nm_q; ph <= 4'd4;
                end else begin
                    nw0 <= nw1; nw1 <= nw2; nw2 <= nm_q;
                    if (t == slen(sc) - 1) begin
                        t <= 0; ph <= 4'd0;
                        if (sc == 2'd3) begin
                            sc <= 0; k <= 0; i <= 0; st <= S_DEC0;
                        end else begin
                            sc <= sc + 1; st <= S_EMB;
                        end
                    end else t <= t + 1;
                end
            end

            // ---- decomposition: 25-tap running mean, replicate padding -----
            S_DEC0: begin
                if (ph == 4'd0) ph <= 4'd1;
                else begin
                    for (n = 0; n < DM; n = n + 1)
                        wsum[n] <= wsum[n] + $signed(lane(am_q, n));
                    if (i == 10'd24) begin i <= 0; t <= 0; ph <= 0; st <= S_DEC; end
                    else i <= i + 1;
                end
            end
            S_DEC: begin
                if (ph == 4'd0) ph <= 4'd1;
                else if (ph == 4'd1) begin
                    dcur <= am_q; ph <= 4'd2;
                end else if (ph == 4'd2) begin
                    dadd <= am_q; ph <= 4'd3;
                end else begin
                    for (n = 0; n < DM; n = n + 1)
                        wsum[n] <= wsum[n] + $signed(lane(dadd, n)) -
                                   $signed(lane(am_q, n));
                    if (t == slen(sc) - 1) begin
                        t <= 0; ph <= 4'd0;
                        for (n = 0; n < DM; n = n + 1) wsum[n] <= 0;
                        if (sc == 2'd3) begin
                            sc <= 0; lev <= 0; dir <= 0; st <= S_MIXA;
                        end else begin
                            sc <= sc + 1; i <= 0; st <= S_DEC0;
                        end
                    end else begin
                        t <= t + 1; ph <= 4'd1;
                    end
                end
            end

            // ---- season / trend mixing ------------------------------------
            S_MIXA: begin
                o <= 0; t <= 0; ph <= 0;
                for (n = 0; n < DM; n = n + 1) acc[n] <= 0;
                st <= S_MIXB;
            end
            // first layer, one output row at a time
            S_MIXB: begin
                if (ph == 4'd0) ph <= 4'd1;
                else begin
                    for (n = 0; n < DM; n = n + 1)
                        acc[n] <= acc[n] + $signed(wm_q) *
                            $signed(lane((dir == 2'd0) ? sm_q : tm_q, n));
                    if (t == mlen(dir, lev) - 8'd1) begin
                        t <= 0; ph <= 4'd0; st <= S_MIXG;
                    end else t <= t + 1;
                end
            end
            S_MIXG: begin
                for (n = 0; n < DM; n = n + 1) acc[n] <= 0;
                if (o == mout(dir, lev) - 8'd1) begin
                    o <= 0; ph <= 4'd2; st <= S_MIXG2;
                end else begin o <= o + 1; ph <= 4'd0; st <= S_MIXB; end
            end
            // GELU over the whole first-layer output
            S_MIXG2: begin
                if (o == mout(dir, lev) - 8'd1) begin
                    o <= 0; t <= 0; ph <= 4'd3; st <= S_MIXC;
                end else o <= o + 1;
            end
            // second layer, one output row at a time, added into the destination
            S_MIXC: begin
                for (n = 0; n < DM; n = n + 1)
                    acc[n] <= acc[n] + $signed(wm_q) * $signed(lane(rm_q, n));
                if (t == mout(dir, lev) - 8'd1) begin
                    t <= 0; ph <= 4'd3; st <= S_COMB;
                end else t <= t + 1;
            end

            S_COMB: begin
                for (n = 0; n < DM; n = n + 1) acc[n] <= 0;
                if (o == mout(dir, lev) - 8'd1) begin
                    o <= 0; t <= 0; ph <= 4'd0;
                    if (lev == 2'd2) begin
                        if (dir == 2'd0) begin dir <= 1; lev <= 0; st <= S_MIXA; end
                        else st <= S_COMB2;
                    end else begin lev <= lev + 1; st <= S_MIXA; end
                end else begin
                    o <= o + 1; t <= 0; st <= S_MIXC;
                end
            end

            // ---- sum season and trend -------------------------------------
            S_COMB2: begin
                if (t == 8'd179) begin
                    t <= 0; sc <= 0; grp <= 0; ph <= 4'd0; st <= S_GATE1;
                end else t <= t + 1;
            end

            // ---- gate: 16 channels -> 32 -> 16 ----------------------------
            S_GATE1: begin
                if (ph == 4'd0) begin
                    for (n = 0; n < DM; n = n + 1) acc[n] <= 0;
                    c <= 0; ph <= 4'd1;
                end else begin
                    for (n = 0; n < DM; n = n + 1)
                        acc[n] <= acc[n] + $signed(lane(gm_q, n)) *
                                            $signed(lane(sm_q, c));
                    if (c == 8'd15) begin c <= 0; ph <= 4'd0; st <= S_GATG; end
                    else c <= c + 1;
                end
            end
            S_GATG: begin
                for (n = 0; n < DM; n = n + 1)
                    hid[grp*16 + n] <= gelu_of(sat((acc[n] >>> WQ) +
                        ($signed(lane(gm_q, n)) >>> (WQ - DQ))));
                ph <= 4'd0;
                if (grp == 2'd1) begin grp <= 0; ph <= 4'd3; st <= S_GATE2; end
                else begin grp <= grp + 1; st <= S_GATE1; end
            end
            S_GATE2: begin
                if (ph == 4'd3) begin
                    for (n = 0; n < DM; n = n + 1) acc[n] <= 0;
                    o <= 0; ph <= 4'd4;
                end else begin
                    for (n = 0; n < DM; n = n + 1)
                        acc[n] <= acc[n] + $signed(lane(gm_q, n)) * $signed(hid[o]);
                    if (o == DFF - 1) begin o <= 0; ph <= 4'd5; st <= S_GATE3; end
                    else o <= o + 1;
                end
            end

            // ---- gate result back into the residual ----------------------
            S_GATE3: begin
                ph <= 4'd0;
                if (t == slen(sc) - 1) begin
                    t <= 0;
                    if (sc == 2'd3) begin
                        sc <= 0;
                        if (k == 2'd1) begin st <= S_PRED; o <= 0; ph <= 4'd0; end
                        else begin k <= k + 1; i <= 0; st <= S_DEC0; end
                    end else begin sc <= sc + 1; st <= S_GATE1; end
                end else begin
                    t <= t + 1; st <= S_GATE1;
                end
            end

            // ---- prediction -----------------------------------------------
            S_PRED: begin
                if (ph == 4'd0) begin
                    for (n = 0; n < DM; n = n + 1) acc[n] <= 0;
                    t <= 0; ph <= 4'd1;
                end else if (ph == 4'd1) begin
                    for (n = 0; n < DM; n = n + 1)
                        acc[n] <= acc[n] + $signed(wm_q) * $signed(lane(am_q, n));
                    if (t == slen(sc) - 1) begin t <= 0; ph <= 4'd2; end
                    else t <= t + 1;
                end else if (ph == 4'd2) begin
                    for (n = 0; n < DM; n = n + 1)
                        prow[n*16 +: 16] <= sat((acc[n] >>> WQ) +
                            ($signed(wm_q) >>> (WQ - DQ)));
                    ph <= 4'd3; t <= 0;
                    for (n = 0; n < DM; n = n + 1) acc[n] <= 0;
                end else if (ph == 4'd3) begin
                    projb <= wm_q;
                    ph <= 4'd4; t <= 0;
                end else begin
                    // the last product has to be inside the total, not in the
                    // accumulator that is still one cycle behind
                    psum = sum1 + $signed(wm_q) * $signed(lane(prow, t));
                    if (t == DM - 1) begin
                        outv[o] <= sat($signed(outv[o]) +
                            sat((psum >>> WQ) + ($signed(projb) >>> (WQ - DQ))));
                        sum1 <= 0;
                        ph <= 4'd0;
                        if (o == PRED - 1) begin
                            o <= 0;
                            if (sc == 2'd3) begin sc <= 0; st <= S_DEN; end
                            else begin sc <= sc + 1; st <= S_PRED; end
                        end else begin o <= o + 1; st <= S_PRED; end
                    end else begin sum1 <= psum; t <= t + 1; end
                end
            end

            S_DEN: begin
                outv[o] <= sat((($signed(outv[o]) * $signed(stdv[0])) >>> DQ) + $signed(meanv[0]));
                if (o == PRED - 1) begin o <= 0; st <= S_DONE; end
                else o <= o + 1;
            end

            S_DONE: ;
            default: st <= S_IDLE;
            endcase
        end
    end

endmodule
